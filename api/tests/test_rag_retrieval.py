def test_config_invalid_limits_fail_to_defaults(monkeypatch):
    for name, value in {"RAG_CANDIDATE_LIMIT": "bad", "RAG_MAX_SOURCES": "0",
                        "RAG_CONTEXT_MAX_BYTES": "999999", "RAG_SOURCE_INDEX": "*"}.items():
        monkeypatch.setenv(name, value)
    config = RagConfig.from_env()
    assert (config.candidate_limit, config.max_sources, config.context_max_bytes) == (30, 6, 16000)
    assert config.source_index == "podcast_clips"
