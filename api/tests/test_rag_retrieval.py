def hit(text="machine learning " * 40, start=0, end=120000, episode="ep1", score=5, index=0):
    return {"_id": "autogenerated", "_score": score, "highlight": {"clip_text": ["WRONG EXCERPT"]},
            "_source": {"podcast_id": "show1", "episode_id": episode, "clip_index": index,
                        "clip_start_ms": start, "clip_end_ms": end, "clip_text": text,
                        "speakers": [2, 1, 2]}}


def clients(hits):
    es, pool = AsyncMock(), AsyncMock()
    es.search.return_value = {"hits": {"hits": hits}}
    pool.fetchrow.return_value = {"show_name": "Real Show", "episode_name": "Real Episode",
                                 "audio_link": None}
    return es, pool


@pytest.mark.asyncio
async def test_bm25_full_text_and_metadata():
    doc = hit()
    es, pool = clients([doc])
    result = await retrieve("machine learning", es, pool, RagConfig())
    body = es.search.call_args.kwargs["body"]
    assert body["query"] == build_query("machine learning", 0, 30)["query"]
    assert "highlight" not in body and "clip_text" in body["_source"]
    assert body["size"] == 30
    assert es.search.call_args.kwargs["index"] == "podcast_clips"
    source = result[0]
    assert source.excerpt == doc["_source"]["clip_text"] and len(source.excerpt) > 300
    assert source.show_name == "Real Show" and source.episode_name == "Real Episode"
    assert source.metadata_available and source.speakers == [1, 2]
    assert source.clip_index == 0 and source.clip_end_ms == 120000
    pool.fetchrow.assert_awaited_once()


def test_chunk_id_stable_and_content_sensitive():
    doc = hit()
    original = parse_hit(doc)
    doc["_id"] = "different-id"
    doc["_source"]["clip_index"] = 99
    assert parse_hit(doc).chunk_id == original.chunk_id
    assert replace(original, text=original.text + " ").chunk_id != original.chunk_id
    assert replace(original, episode_id="other").chunk_id != original.chunk_id
    assert decode_chunk_id(original.chunk_id)[:4] == ["show1", "ep1", 0, 120000]


def test_deduplicate_and_deterministic_order():
    one = parse_hit(hit())
    duplicate = replace(one, clip_index=4)
    two = parse_hit(hit(episode="ep2"))
    forward = select_context([duplicate, two, one], 6, 16000)
    reverse = select_context([one, two, duplicate], 6, 16000)
    assert forward == reverse
    assert len(forward) == 2
    assert next(c for c in forward if c.episode_id == "ep1").clip_index == 0


def test_overlap_suppresses_adjacent_but_preserves_other_episode():
    one = parse_hit(hit(end=119800, score=10))
    adjacent = parse_hit(hit(start=60000, end=179800, score=9))
    far = parse_hit(hit(start=120000, end=239800, score=8))
    other_episode = parse_hit(hit(episode="ep2", score=7))
    assert select_context([adjacent, other_episode, far, one], 6, 16000) == [one, far, other_episode]


def test_source_limit():
    candidates = [parse_hit(hit(episode=f"ep{i}")) for i in range(10)]
    assert len(select_context(candidates, 3, 16000)) == 3


def test_utf8_budget_skips_oversized_without_truncation():
    large = parse_hit(hit(text="x" * 101, score=10))
    one = parse_hit(hit(text="汉" * 20, episode="ep2", score=9))
    two = parse_hit(hit(text="z" * 40, episode="ep3", score=8))
    extra = parse_hit(hit(text="a", episode="ep4", score=7))
    selected = select_context([large, one, two, extra], 6, 100)
    assert selected == [one, two]
    assert sum(evidence_size(c.text) for c in selected) == 100


