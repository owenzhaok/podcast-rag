@pytest.mark.asyncio
async def test_resolver_pages_and_cap():
    original = parse_hit(hit(text="original"))
    es, pool = clients([])
    wrong = hit(text="changed")
    es.search.side_effect = [{"hits": {"hits": [wrong] * 100}},
                             {"hits": {"hits": [hit(text="original")]}}]
    assert (await resolve(original.chunk_id, es, pool, RagConfig())).excerpt == "original"
    es.search.side_effect = None
    es.search.return_value = {"hits": {"hits": [wrong] * 100}}
    with pytest.raises(RetrievalUnavailable):
        await resolve(original.chunk_id, es, pool, RagConfig())


