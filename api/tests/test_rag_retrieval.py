@pytest.mark.asyncio
async def test_source_resolution_checks_exact_hash_and_fixed_index():
    doc = hit()
    es, pool = clients([doc])
    chunk_id = parse_hit(doc).chunk_id
    source = await resolve(chunk_id, es, pool, RagConfig())
    assert source.chunk_id == chunk_id and source.excerpt == doc["_source"]["clip_text"]
    assert es.search.call_args.kwargs["index"] == "podcast_clips"
    assert "filter" in es.search.call_args.kwargs["body"]["query"]["bool"]
    doc["_source"]["clip_text"] = "changed text"
    assert await resolve(chunk_id, es, pool, RagConfig()) is None


