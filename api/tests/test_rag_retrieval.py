@pytest.mark.asyncio
async def test_enabled_ask_without_keys_and_source_route(enabled_app):
    app, es, pool, cache = enabled_app
    with patch("socket.socket.connect", side_effect=AssertionError("No external provider allowed")):
        async with AsyncClient(transport=ASGITransport(app=app), base_url="http://test") as client:
            response = await client.post("/ask", json={"question": "machine learning"})
            assert response.status_code == 200
            body = response.json()
            assert body["status"] == "generation_unavailable" and body["answer"] is None
            assert body["reason"] == "llm_not_configured" and body["retrieval_mode"] == "bm25"
            source = body["sources"][0]
            resolved = await client.get("/sources/" + source["chunk_id"])
            assert resolved.status_code == 200 and resolved.json() == source
            es.search.return_value = {"hits": {"hits": []}}
            assert (await client.get("/sources/" + source["chunk_id"])).status_code == 404
            empty = await client.post("/ask", json={"question": "unknown"})
            assert empty.json()["status"] == "insufficient_context"
            es.search.side_effect = OSError("private connection detail")
            failure = await client.post("/ask", json={"question": "question"})
            assert failure.status_code == 503 and failure.json() == {"detail": "retrieval_unavailable"}
            assert (await client.get("/sources/" + source["chunk_id"])).status_code == 503
            assert (await client.get("/health")).json() == {"status": "ok"}
    assert not cache.mock_calls


